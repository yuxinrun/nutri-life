type FoodInput = Omit<Food, 'kind' | 'sections' | 'nutritionSource' | 'categoryName'> & {
  nutritionSource?: Reference;
  extraSections?: Food['sections'];
};

function buildFood(input: FoodInput): Food {
  const sections: Food["sections"] = [
    {
      id: "nutrition",
      heading: "营养特点",
      paragraphs: input.highlights,
      callout: {
        type: "science",
        text: `数据口径：${input.state}；${input.ediblePortion}；${input.measurement}。不同数据库数值不可直接混用。`,
      },
    },
    { id: "selection", heading: "选购技巧", paragraphs: input.selection },
    { id: "storage", heading: "保存方法", paragraphs: input.storage },
    { id: "cooking", heading: "烹饪建议", paragraphs: input.cooking },
    { id: "pairing", heading: "适合搭配", paragraphs: input.pairings },
    {
      id: "myths",
      heading: "常见误区",
      bullets: input.myths.map((m) => `“${m.claim}”：${m.correction}`),
    },
    ...(input.extraSections ?? []),
  ];
  return {
    ...input,
    kind: "food",
    categoryName: input.category,
    nutritionSource: input.nutritionSource ?? usda,
    sections,
  };
}

