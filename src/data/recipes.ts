type RecipeInput = Omit<Recipe, "kind" | "sections" | "nutritionNote" | "categoryName">;

function buildRecipe(input: RecipeInput): Recipe {
  return {
    ...input,
    kind: "recipe",
    categoryName: input.category,
    nutritionNote: `营养数据为按食材用量与公开营养数据库进行的计算估算（${input.nutritionEstimate?.basis ?? "未逐项计算"}），未经过实验室检测，仅供了解大致构成；实际值因食材品种、称量与烹调损耗而变化。`,
    sections: [
      {
        id: "why",
        heading: "这道食谱的特点",
        paragraphs: [input.summary],
      },
      {
        id: "ingredients",
        heading: "食材清单",
        paragraphs: ["以下用量按标注人数计算；调味料可按口味微调，但钠含量会随用量变化。"],
        table: {
          head: ["食材", "用量", "备注"],
          rows: input.ingredients.map((i) => [i.name, i.amount, i.optional ? "可选" : i.foodSlug ? "可参考对应食物百科" : "常规食材"]),
        },
      },
      {
        id: "steps",
        heading: "制作步骤",
        steps: input.steps,
      },
      {
        id: "nutrition",
        heading: "营养说明",
        paragraphs: [
          `每份约含能量 ${input.nutritionEstimate?.energyKcal ?? "—"} kcal、蛋白质 ${input.nutritionEstimate?.proteinG ?? "—"} g、脂肪 ${input.nutritionEstimate?.fatG ?? "—"} g、碳水化合物 ${input.nutritionEstimate?.carbsG ?? "—"} g。数值为计算估算，未经过实验室检测。`,
        ],
        callout: { type: "caution", text: "估算不等于检测：以上数值根据食材用量计算，不能作为医学处方或精确摄入记录。" },
      },
      {
        id: "substitutes",
        heading: "替代食材与过敏原",
        paragraphs: [`过敏原提示：${input.allergens.join("、") || "无常见过敏原"}。`, `可选替代：${input.substitutes.join("；")}。`],
      },
      {
        id: "storage",
        heading: "保存与复热",
        paragraphs: input.storage,
      },
      { id: "tips", heading: "操作要点", bullets: input.tips },
    ],
  };
}

